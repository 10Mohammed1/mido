#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Regenerate ``requirements.lock.txt`` from the real dependency resolver.

The old lock file was a raw ``pip freeze`` of a Fedora system Python: it
contained packages that have nothing to do with Mido (cockpit, blivet, …) and
Fedora-only ``@ file:///builddir/...`` entries that cannot be installed
anywhere.  This script instead asks pip to *resolve* ``requirements.txt`` and
writes the resulting versions, so the lock is reproducible and installable.

Usage::

    python tools/make_lock.py            # write requirements.lock.txt
    python tools/make_lock.py --check    # fail if the file is out of date

Notes
-----
* The lock reflects the platform it was generated on (Linux in CI/development).
  ``requirements.lock.txt`` therefore lists the Linux-only extras
  (py-tgcalls / pyrofork / mautrix); Windows installs use ``requirements.txt``.
* Resolution is done by pip itself (``--dry-run --report``), which needs
  network access but never installs anything.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQUIREMENTS = ROOT / "requirements.txt"
LOCK = ROOT / "requirements.lock.txt"
HEADER = """\
# ══════════════════════════════════════════════════════════════════════════════
#  Mido · fully resolved dependency lock
#
#  Generated by:  python tools/make_lock.py
#  Source:        requirements.txt (pinned direct dependencies)
#  Method:        pip install --dry-run --report  (real resolver, no installs)
#  Platform:      {platform} · Python {python}
#  Generated at:  {timestamp}
#
#  - This is a resolution for the platform above; on Windows use
#    requirements.txt (the Linux-only extras below are skipped by markers).
#  - Do not edit by hand.
# ══════════════════════════════════════════════════════════════════════════════
"""

NOTE = """
# ──────────────────────────────────────────────────────────────────────────────
#  Not part of the resolution above — installed separately with --no-deps:
#      pip install --no-deps -r requirements-nodeps.txt
#      googletrans==4.0.0rc1        # last sync-API release; stale httpx==0.13.3
#                                   # pin conflicts with youtube-search-python
# ──────────────────────────────────────────────────────────────────────────────
"""


def resolve() -> list[str]:
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "report.json"
        command = [
            sys.executable,
            "-m",
            "pip",
            "install",
            "--dry-run",
            "--ignore-installed",
            "--quiet",
            "--report",
            str(report),
            "-r",
            str(REQUIREMENTS),
        ]
        completed = subprocess.run(command, capture_output=True, text=True)
        if completed.returncode != 0:
            sys.stderr.write(completed.stdout + completed.stderr)
            raise SystemExit("pip could not resolve requirements.txt")
        payload = json.loads(report.read_text(encoding="utf-8"))
    lines = set()
    for item in payload.get("install", []):
        name = item["metadata"]["name"]
        version = item["metadata"]["version"]
        lines.add(f"{name}=={version}")
    return sorted(lines, key=str.lower)


def render(packages: list[str]) -> str:
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    header = HEADER.format(
        platform=sys.platform,
        python=".".join(str(part) for part in sys.version_info[:3]),
        timestamp=stamp,
    )
    return header + "\n".join(packages) + "\n" + NOTE


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="only verify the lock is current")
    args = parser.parse_args()

    packages = resolve()
    content = render(packages)
    if args.check:
        current = LOCK.read_text(encoding="utf-8") if LOCK.is_file() else ""
        # ignore the timestamp line when comparing
        strip = lambda text: "\n".join(  # noqa: E731
            line for line in text.splitlines() if not line.startswith("#  Generated at")
        )
        if strip(current) != strip(content):
            print("requirements.lock.txt is out of date — run: python tools/make_lock.py")
            return 1
        print(f"requirements.lock.txt is up to date ({len(packages)} packages)")
        return 0

    LOCK.write_text(content, encoding="utf-8")
    print(f"wrote {LOCK.name}: {len(packages)} packages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
